#!/usr/bin/env python3
"""Emit MINIMAL-NETLIST.md from the committed census + verdicts (plan Phase 0 exit criterion (a)).

Every REMOVED net names the references that consumed it, split into REMOVE-set consumers
(the net dies with them) and KEPT consumers (the net and its copper stay, so only the
REMOVE-set fanout is saved). Anything the two files disagree on is a hard error, not a guess.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
audit = json.loads((HERE / "layer_audit.json").read_text())
verdicts = json.loads((HERE / "verdicts.json").read_text())["verdicts"]
prov = json.loads((HERE / "provenance.json").read_text())

REMOVE_SET = {r for r, v in verdicts.items() if v["verdict"] in ("REMOVE", "REPLACE")}
shared = audit["nets_shared_with_removed_refs"]
per_net = audit["per_net_segments"]

# Section A: the census already decided which nets are removed (every pad consumer sits in
# the REMOVE set). Do NOT re-derive it here -- a net whose ONLY consumer is a removed ref
# never appears in `nets_shared_with_removed_refs`, so a re-derivation silently emits an
# empty table (measured: it did).
gone_with_site = []
for net in sorted(audit["removed_nets"]):
    info = per_net.get(net, {})
    if info.get("in_minimal_set", False):
        raise SystemExit(f"CONTRADICTION: census calls {net} removed but also in the MINIMAL set")
    reason = info.get("verdict_reason", "")
    if not reason.startswith("REMOVED:"):
        raise SystemExit(f"CONTRADICTION: {net} in removed_nets without a REMOVED reason: {reason!r}")
    gone_with_site.append((net, reason, info))

# Section B/C: nets kept alive by a KEPT consumer that also land on a removed site.
kept_with_fanout = []
for net, consumers in sorted(shared.items()):
    consumers = [c for c in consumers if c in verdicts or c in ("U_C", "U_E28", "U_LORA1280")]
    if not consumers:
        continue
    remove_side = sorted(c for c in consumers if c in REMOVE_SET or c in ("U_E28", "U_LORA1280"))
    keep_side = sorted(c for c in consumers if c not in REMOVE_SET and c not in ("U_E28", "U_LORA1280"))
    if remove_side and keep_side:
        kept_with_fanout.append((net, remove_side, keep_side, per_net.get(net, {})))

site = audit["site_named_copper"]
lines = [
    "# MINIMAL net list — what is removed and who consumed it",
    "",
    "Generated by `docs/analysis/vnext-minimal-audit-20261125/minimal_netlist.py` from",
    "`layer_audit.json` (census) + `verdicts.json` (per-reference disposition).",
    "**Do not hand-edit** — regenerate; a diff here means the census or a verdict changed.",
    "",
    f"Reference board: `{prov['ordered_v10']['stage1_reference']}` @ "
    f"`{audit['board_sha256'][:12]}` (v11 stage-1, ADR-089 G3 reference board).",
    f"Full-variant reference set: {len(verdicts)} refs. REMOVE/REPLACE set: "
    f"{', '.join(sorted(REMOVE_SET))}.",
    "",
    "## A. Nets that die with the removed sites (no kept consumer)",
    "",
    "| net | every pad consumer sits on | segments on board |",
    "|---|---|---|",
]
for net, reason, stats in gone_with_site:
    consumers = reason.split("every pad consumer is on", 1)[-1].split("(REMOVE set")[0].strip()
    lines.append(f"| `{net}` | {consumers} | {stats.get('segments', 0)} |")
if not gone_with_site:
    lines.append("| — | none | — |")

lines += [
    "",
    "All four are `U_C` control nets and all four are **unrouted on this board** (0 segments).",
    "ADR-145's 19.81 mm is the PAD SPAN of U_C's control pads, not routed copper. So removing",
    "`U_C` deletes **no routed track length** here; it frees the footprint area and the",
    "inner-layer space its fanout would have needed on a rebuild.",
    "",
    "## B. Site-named copper that goes with the site (net serves the site + the MCU)",
    "",
    "| net | removed-site consumer | kept consumer | segments |",
    "|---|---|---|---|",
]
for net, remove_side, keep_side, stats in kept_with_fanout:
    if net.startswith(("/E28_", "/LORA1280_", "/U_C_")):
        lines.append(
            f"| `{net}` | {', '.join(remove_side)} | {', '.join(keep_side)} | "
            f"{stats.get('segments', 0)} |"
        )
lines += [
    "",
    f"Site-named copper totals **{site['total_segments']} segments / "
    f"{site['total_length_mm']:.2f} mm / {site['vias']} vias** across "
    + ", ".join(f"{l} {v['length_mm']:.2f} mm" for l, v in site["per_layer"].items())
    + ".",
    f"Against {sum(v['track_length_mm'] for v in audit['per_layer'].values()):.2f} mm of total routed",
    "track on the board, that is the routing relief a MINIMAL rebuild actually banks. It is",
    "**fanout to module pins, not the module's internal network** — it does not prove any outline.",
    "",
    "## C. Nets that stay because a KEPT reference still touches them",
    "",
    "| net | REMOVE-set consumer | KEPT consumers |",
    "|---|---|---|",
]
for net, remove_side, keep_side, _ in kept_with_fanout:
    if not net.startswith(("/E28_", "/LORA1280_", "/U_C_")):
        lines.append(f"| `{net}` | {', '.join(remove_side)} | {', '.join(keep_side)} |")

lines += [
    "",
    "These keep their copper and must keep it after the site is deleted. In particular",
    "`/SPI1_*` is shared with `U3` (the retained LR2021 RX), and `/VTCXO_VNTC` is shared with",
    "`U3` — **trace it before deleting anything on a rebuild**: `U_C`'s VTCXO/VNTC connection",
    "is unresolved in function (see `VNEXT-MINIMAL-PLAN.md` and the earlier brief), so the",
    "`U3` end is the one that survives and the `U_C` end must be terminated, not left floating.",
    "",
    "## Exit criterion",
    "",
    "Plan Phase 0 exit criterion (a) — a committed list naming every removed net and the ref",
    "that consumed it — is satisfied by sections A and B. Criterion (b) — no net removed that a",
    "KEPT reference still touches — is satisfied mechanically: sections A+B contain only nets",
    "whose every consumer is in the REMOVE set, and this script refuses to emit a net into A or B",
    "while any kept reference touches it.",
    "",
]
out = HERE / "MINIMAL-NETLIST.md"
out.write_text("\n".join(lines))
print(f"WROTE {out}  ({len(gone_with_site)} dead nets, {len(kept_with_fanout)} shared nets)")