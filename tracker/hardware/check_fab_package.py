#!/usr/bin/env python3
"""Verify the committed fab package is the package of the board that is actually on the branch.

A fab package is only verified against the board it was generated from. Earlier in this project the
package was regenerated once, the board then changed twice, and the "layers byte-identical" check
silently expired: it kept saying PASS about a board nobody was shipping. So the check now states
which board it compared against, and fails loudly when the package and the board disagree.

Runs with no KiCad and no network. Compares the drill hole set, which is the part of the package
that encodes geometry most directly and cannot be regenerated by accident.

Usage:
    python3 tracker/hardware/check_fab_package.py
    python3 tracker/hardware/check_fab_package.py --package DIR --board FILE
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DEFAULT_BOARD = os.path.join(ROOT, "docs", "analysis", "bulk-route-20261107", "latest.kicad_pcb")
DEFAULT_PKG = os.path.join(ROOT, "docs", "analysis", "bulk-route-20261107", "fab-11opens")

# The board of record this package was generated from. Update together, never separately.
EXPECTED_BOARD_SHA8 = "92ff3705"
EXPECTED_HOLES = 196
EXPECTED_TOOL_DIAMETERS = {"0.200", "0.300", "1.000", "2.500"}


def board_sha8(path):
    """git's blob hash, so the number matches `git hash-object` and every doc that quotes it.

    NOT a plain sha1 of the file: git prefixes `blob <len>\\0` before hashing. Using a bare sha1
    here produced 6420be3f for a board every document calls 92ff3705 -- a check that disagrees with
    the rest of the project is worse than no check.
    """
    import hashlib
    data = open(path, "rb").read()
    h = hashlib.sha1(b"blob %d\0" % len(data))
    h.update(data)
    return h.hexdigest()[:8]


def parse_excellon(path):
    """Return (holes, tools). `T<n>` lines SELECT a tool; `T<n>C<d>` DEFINES one.

    Getting this wrong is how an earlier parser reported 0 holes at 0.200 mm: it attributed every
    hole to the last *definition* instead of the currently selected tool.
    """
    tools, holes, cur = {}, [], None
    for line in open(path, errors="replace"):
        line = line.strip()
        m = re.match(r"^T(\d+)(?:C([0-9.]+))?$", line)
        if m:
            num, dia = m.group(1), m.group(2)
            if dia is not None:
                tools[num] = dia
            else:
                cur = num
            continue
        m = re.match(r"^X(-?[0-9.]+)Y(-?[0-9.]+)", line)
        if m:
            holes.append((cur, m.group(1), m.group(2)))
    return holes, tools


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", default=DEFAULT_BOARD)
    ap.add_argument("--package", default=DEFAULT_PKG)
    ap.add_argument("--expect-board", default=EXPECTED_BOARD_SHA8)
    args = ap.parse_args()

    fails = []

    if not os.path.exists(args.board):
        print(f"FAIL board missing: {args.board}")
        return 2
    actual = board_sha8(args.board)
    print(f"board on branch : {actual}")
    print(f"package expected: {args.expect_board}")
    if actual != args.expect_board:
        fails.append(
            f"the board is {actual} but this package was generated from {args.expect_board}. "
            "Regenerate the package or update EXPECTED_BOARD_SHA8 -- do not ship a package "
            "built from a different board.")

    drls = [f for f in os.listdir(args.package) if f.lower().endswith(".drl")]
    if len(drls) != 1:
        print(f"FAIL expected exactly 1 drill file in {args.package}, found {len(drls)}")
        return 1
    holes, tools = parse_excellon(os.path.join(args.package, drls[0]))
    print(f"drill           : {len(holes)} holes, {len(tools)} tools ({drls[0]})")

    if len(holes) != EXPECTED_HOLES:
        fails.append(f"drill has {len(holes)} holes, expected {EXPECTED_HOLES}")

    dias = {tools.get(t, "?") for t, _, _ in holes}
    print(f"tool diameters  : {sorted(dias)}")
    if not dias <= EXPECTED_TOOL_DIAMETERS:
        fails.append(f"unexpected drill diameters {sorted(dias - EXPECTED_TOOL_DIAMETERS)}; "
                     "JLCPCB standard tools are 0.200/0.300/1.000/2.500 here")

    n_files = len(os.listdir(args.package))
    print(f"package files   : {n_files}")
    if n_files != 28:
        fails.append(f"package has {n_files} files, expected 28")

    print()
    if fails:
        for f in fails:
            print(f"FAIL {f}")
        return 1
    print("PASS fab package matches the board on the branch")
    return 0


if __name__ == "__main__":
    sys.exit(main())
